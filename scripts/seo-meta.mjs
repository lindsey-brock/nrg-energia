export const SITE = 'https://www.nrg-energia.com';
const CLOUD = 'https://res.cloudinary.com/dmegrbq5k/image/upload';

/** Cloudinary treats , and / as delimiters inside l_text, so they need escaping. */
function ogText(s = '') {
  return encodeURIComponent(
    String(s)
      .replace(/<[^>]+>/g, '')
      .replace(/&mdash;/g, '—').replace(/&rsquo;/g, '’').replace(/&amp;/g, '&')
      .replace(/&egrave;/g, 'è').replace(/&eacute;/g, 'é').replace(/&agrave;/g, 'à')
      .replace(/&ugrave;/g, 'ù').replace(/&ograve;/g, 'ò')
      .replace(/&laquo;/g, '«').replace(/&raquo;/g, '»')
      .replace(/\s+/g, ' ').trim(),
  // encodeURIComponent already yields %2C and %2F; Cloudinary decodes the path
  // once more, so these must be double-encoded or they act as delimiters.
  ).replace(/%2C/g, '%252C').replace(/%2F/g, '%252F');
}

const clamp = (s, n) => (s.length > n ? `${s.slice(0, n - 1).trimEnd()}…` : s);

/**
 * A photo card: the page's own image, darkened, with the title and a subtitle.
 * Used for blog posts and for section pages that have a hero photograph.
 */
export function photoCard(publicId, title, subtitle = '') {
  const layers = [
    'c_fill,g_auto,w_1200,h_630',
    // colorize rather than a scrim layer: l_one_pixel is not an asset in this
    // account, and darkening the whole frame keeps white text readable anywhere
    'e_colorize:48,co_rgb:0a1912',
    `l_text:Arial_60_bold:${ogText(clamp(title, 70))},co_white,w_1020,c_fit/fl_layer_apply,g_south_west,x_60,y_${subtitle ? 158 : 74}`,
  ];
  if (subtitle) {
    layers.push(`l_text:Arial_30:${ogText(clamp(subtitle, 96))},co_rgb:cfe6d7,w_1020,c_fit/fl_layer_apply,g_south_west,x_60,y_64`);
  }
  return `${CLOUD}/${layers.join('/')}/${publicId}`;
}

/**
 * Brand cards are pre-rendered to og/*.jpg by scripts/make-og-cards.mjs, using
 * headless Chrome so they carry the real dot-grid mark and the Syne wordmark.
 * Cloudinary can only set type in fonts it hosts, which meant Arial.
 */
export function brandAsset(name) {
  return `${SITE}/og/${name}.jpg`;
}


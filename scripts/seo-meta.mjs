/** The <meta> and <link> block for one side of a page pair. */
export function metaBlock({ lang, self, alt, title, description, ogImage, type = 'website' }) {
  const locale = lang === 'it' ? 'it_IT' : 'en_GB';
  return [
    `  <link rel="canonical" href="${SITE}${self}"/>`,
    `  <link rel="alternate" hreflang="it" href="${SITE}${alt.it}"/>`,
    `  <link rel="alternate" hreflang="en" href="${SITE}${alt.en}"/>`,
    `  <link rel="alternate" hreflang="x-default" href="${SITE}${alt.it}"/>`,
    `  <meta property="og:type" content="${type}"/>`,
    `  <meta property="og:site_name" content="NRG Energia"/>`,
    `  <meta property="og:locale" content="${locale}"/>`,
    `  <meta property="og:url" content="${SITE}${self}"/>`,
    `  <meta property="og:title" content="${escapeAttr(title)}"/>`,
    `  <meta property="og:description" content="${escapeAttr(description)}"/>`,
    `  <meta property="og:image" content="${ogImage}"/>`,
    `  <meta property="og:image:width" content="1200"/>`,
    `  <meta property="og:image:height" content="630"/>`,
    `  <meta name="twitter:card" content="summary_large_image"/>`,
    `  <meta name="twitter:title" content="${escapeAttr(title)}"/>`,
    `  <meta name="twitter:description" content="${escapeAttr(description)}"/>`,
    `  <meta name="twitter:image" content="${ogImage}"/>`,
  ].join('\n');
}

export function escapeAttr(s = '') {
  return String(s)
    .replace(/&(?![a-zA-Z]+;|#\d+;)/g, '&amp;')
    .replace(/"/g, '&quot;')
    .replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

#!/usr/bin/env node
// Generates admin/italy-map.js — the SVG outline the Andamento map draws on.
//
//   node scripts/make-italy-map.mjs
//
// Source: Natural Earth 1:50m country boundaries (public domain), via the
// world-atlas TopoJSON build. Vendoring the finished path keeps the admin
// free of a runtime map dependency; rerun this only to change the projection
// or the simplification tolerance.

import { writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const SRC = 'https://cdn.jsdelivr.net/npm/world-atlas@2/countries-50m.json';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

// ── minimal TopoJSON reader: quantised, delta-encoded arcs ─────────────────
function decodeArcs(topo) {
  const [sx, sy] = topo.transform.scale;
  const [tx, ty] = topo.transform.translate;
  return topo.arcs.map((arc) => {
    let x = 0, y = 0;
    return arc.map(([dx, dy]) => {
      x += dx; y += dy;
      return [x * sx + tx, y * sy + ty];
    });
  });
}

/** A ring is a list of arc indices; a negative index means "that arc, reversed". */
function ring(indices, arcs) {
  const pts = [];
  for (const i of indices) {
    const a = i < 0 ? [...arcs[~i]].reverse() : arcs[i];
    pts.push(...(pts.length ? a.slice(1) : a));
  }
  return pts;
}

// ── Douglas-Peucker, so the vendored path stays a few KB ───────────────────
function simplify(points, tolerance) {
  if (points.length < 3) return points;
  const sqTol = tolerance * tolerance;
  const sqSegDist = ([px, py], [x1, y1], [x2, y2]) => {
    let x = x1, y = y1, dx = x2 - x, dy = y2 - y;
    if (dx || dy) {
      const t = ((px - x) * dx + (py - y) * dy) / (dx * dx + dy * dy);
      if (t > 1) { x = x2; y = y2; } else if (t > 0) { x += dx * t; y += dy * t; }
    }
    return (px - x) ** 2 + (py - y) ** 2;
  };
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [first, last] = stack.pop();
    let maxSq = 0, index = 0;
    for (let i = first + 1; i < last; i++) {
      const sq = sqSegDist(points[i], points[first], points[last]);
      if (sq > maxSq) { index = i; maxSq = sq; }
    }
    if (maxSq > sqTol) { keep[index] = 1; stack.push([first, index], [index, last]); }
  }
  return points.filter((_, i) => keep[i]);
}

// ── projection ─────────────────────────────────────────────────────────────
// Web Mercator, then fitted to the viewBox. Italy spans enough latitude that
// an equirectangular projection visibly squashes the north.
// Both axes must be in the same units: x is longitude in radians, not degrees.
const merc = ([lon, lat]) => [
  (lon * Math.PI) / 180,
  Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360)),
];

const WIDTH = 420, HEIGHT = 560, PAD = 10;

async function main() {
  const topo = await (await fetch(SRC)).json();
  const arcs = decodeArcs(topo);
  const italy = topo.objects.countries.geometries.find((g) => g.properties?.name === 'Italy');
  if (!italy) throw new Error('Italy not found in the source topology');

  // MultiPolygon -> rings, dropping specks (a ring's bbox area in degrees²)
  const polygons = italy.type === 'MultiPolygon' ? italy.arcs : [italy.arcs];
  let rings = polygons.map((poly) => ring(poly[0], arcs));      // outer ring only
  rings = rings.filter((r) => {
    const xs = r.map((p) => p[0]), ys = r.map((p) => p[1]);
    return (Math.max(...xs) - Math.min(...xs)) * (Math.max(...ys) - Math.min(...ys)) > 0.05;
  });

  const projected = rings.map((r) => simplify(r.map(merc), 0.0006));
  const all = projected.flat();
  const xs = all.map((p) => p[0]), ys = all.map((p) => p[1]);
  const [x0, x1] = [Math.min(...xs), Math.max(...xs)];
  const [y0, y1] = [Math.min(...ys), Math.max(...ys)];
  const k = Math.min((WIDTH - PAD * 2) / (x1 - x0), (HEIGHT - PAD * 2) / (y1 - y0));
  const ox = (WIDTH - (x1 - x0) * k) / 2, oy = (HEIGHT - (y1 - y0) * k) / 2;
  // y is flipped: SVG grows downward, latitude grows upward
  const place = ([x, y]) => [ox + (x - x0) * k, oy + (y1 - y) * k];

  const d = projected.map((r) =>
    `M${r.map(place).map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join('L')}Z`).join('');

  // the same projection, exported so the page can place city bubbles
  const params = { width: WIDTH, height: HEIGHT, k, ox, oy, x0, y1 };

  const out = `// Generated by scripts/make-italy-map.mjs — do not edit by hand.
// Outline: Natural Earth 1:50m (public domain) via world-atlas.
export const ITALY_VIEWBOX = '0 0 ${WIDTH} ${HEIGHT}';
export const ITALY_PATH = '${d}';
const P = ${JSON.stringify(params)};
/** [lon, lat] -> [x, y] in the viewBox above. */
export function project(lon, lat) {
  const x = (lon * Math.PI) / 180;
  const y = Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360));
  return [P.ox + (x - P.x0) * P.k, P.oy + (P.y1 - y) * P.k];
}
`;
  await writeFile(join(ROOT, 'admin/italy-map.js'), out, 'utf8');
  console.log(`admin/italy-map.js — ${rings.length} rings, ${(out.length / 1024).toFixed(1)} KB`);
}

main().catch((e) => { console.error(e.message); process.exit(1); });
